#!/usr/bin/env python3
"""Generates RetroCal's own textures (leather grain, torn-paper fringes, resize glyph) from random noise.
No third-party artwork is used: only statistics were matched (grain contrast ~5.5 grey levels, correlation length ~1.5 px,
slightly longer horizontally). Output: Sources/RetroCal/MLCalendarAssets.swift (PNGs as base64). Seeded, so it is reproducible.
usage: python3 Reference/gen_assets.py
"""
import base64, io, os
import numpy as np
from PIL import Image

rng = np.random.default_rng(20261012)

def b64(img):
    b = io.BytesIO(); img.save(b, "PNG", optimize=True); return base64.b64encode(b.getvalue()).decode()

def blur_fft(a, sx, sy):
    """Gaussian blur on a torus (keeps tiles seamless)."""
    h, w = a.shape
    fy = np.fft.fftfreq(h)[:, None]; fx = np.fft.fftfreq(w)[None, :]
    k = np.exp(-2 * (np.pi ** 2) * ((sx * fx) ** 2 + (sy * fy) ** 2))
    return np.fft.ifft2(np.fft.fft2(a) * k).real

def _unused_worley_height(n, cells):
    """Pebbled-leather height: distance to the nearest of `cells` random points on a torus."""
    pts = rng.random((cells, 2)) * n
    ys, xs = np.mgrid[0:n, 0:n]
    best = np.full((n, n), 1e9)
    for px, py in pts:
        dx = np.abs(xs - px); dx = np.minimum(dx, n - dx)
        dy = np.abs(ys - py); dy = np.minimum(dy, n - dy)
        best = np.minimum(best, np.hypot(dx, dy))
    return best

def leather(n=512):
    """512 px tile (large, so the repetition is not visible). Fine crisp grain with soft pebbles; no large blotches."""
    noise = blur_fft(rng.standard_normal((n, n)), 1.0, 0.7)             # fine, horizontally elongated grain
    bump = blur_fft(rng.standard_normal((n, n)), 0.9, 0.9)              # pebble height field
    emb = np.roll(bump, -1, 0) - np.roll(bump, 1, 0)                    # light from the top
    d = 0.85 * noise / noise.std() + 0.50 * emb / emb.std()
    d = (d - d.mean()) / d.std()
    d = d - 0.16 * (d * d - 1)                                          # slight negative skew: more dark pores than light flecks
    d = (d - d.mean()) / d.std() * 5.0                                  # grey levels of contrast
    base = 190.0
    out = np.zeros((n, n, 4), np.uint8)
    pos = d >= 0
    a = np.where(pos, d / (255 - base), -d / base)
    out[..., :3] = np.where(pos[..., None], 255, 0)
    out[..., 3] = np.clip(a * 255, 0, 255)
    return Image.fromarray(out)

def fringe(w, depth, seed):
    """One torn-paper bump under the rule, sized after the reference: 60-90 px wide, only 4-6 px deep, flat and wide.
    Inside: grainy light grey (grey values 200-245 on white, i.e. alpha 0.04-0.20 of dark); along the lower edge a row of darker
    speckles (alpha up to 0.35 on about 60 % of the pixels); the outline wobbles by up to one pixel."""
    r = np.random.default_rng(seed)
    h = int(depth) + 3
    xs = np.linspace(-1, 1, w)
    wob = np.round(blur_fft(r.standard_normal((1, w)), 1.2, 0.1)[0] / 0.4 * 0.6)          # +-1 px irregularity
    prof = depth * np.clip(1 - np.abs(xs) ** 2.3, 0, 1) ** 0.75 + wob * (xs ** 2 < 0.85)
    prof = np.clip(np.round(prof), 0, depth + 1)
    out = np.zeros((h, w, 4), np.uint8)
    out[..., :3] = 60
    for x in range(w):
        d = int(prof[x])
        for y in range(h):
            if y < d:                                                              # inside: grainy light grey
                top = 1 - y / max(d, 1)
                al = r.uniform(0.04, 0.14) + 0.04 * top
            elif y == d and d > 0:                                                  # lower edge: darker speckles
                al = r.uniform(0.10, 0.27) if r.random() < 0.62 else r.uniform(0.0, 0.07)
            else:
                al = 0.0
            out[y, x, 3] = int(min(al, 1) * 255)
    return Image.fromarray(out)

assets = {
    "leatherGrain": leather(),
    "paperA": fringe(86, 6, 1),
    "paperB": fringe(64, 5, 2),
    "paperC": fringe(112, 8, 3),
}
src = ("// Generated by Reference/gen_assets.py from random noise (own artwork, no third-party material). Do not edit by hand.\n"
       "import Foundation\n\nenum MLAssets {\n")
for k, v in assets.items():
    src += f'    static let {k} = "{b64(v)}"\n'
src += "}\n"
dest = os.path.join(os.path.dirname(__file__), "..", "Sources", "RetroCal", "MLCalendarAssets.swift")
open(dest, "w").write(src)
print("wrote", os.path.normpath(dest), len(src), "bytes")
